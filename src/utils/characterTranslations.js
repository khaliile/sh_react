/**
 * Returns character name localized to Arabic if isAr is true
 * @param {object|string} charOrId - character object or id
 * @param {boolean} isAr - whether current language is Arabic
 * @returns {string} localized name
 */
export function getCharacterDisplayName(charOrId, isAr = false) {
  if (!charOrId) return '';
  const id = typeof charOrId === 'string' ? charOrId : charOrId.id;
  const fallback = typeof charOrId === 'object' ? charOrId.name : id;
  if (!isAr) return fallback || id;
  return ANIME_CHARACTERS_AR[id] || fallback || id;
}

