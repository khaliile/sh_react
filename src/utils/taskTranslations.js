/**
 * Localizes a note text to Arabic if isAr is true
 * @param {string} text
 * @param {boolean} isAr
 * @returns {string}
 */
export function translateNote(text, isAr = false) {
  if (!text || typeof text !== 'string') return text || '';
  if (!isAr) return text;
  const trimmed = text.trim();
  return TASK_TRANSLATIONS_AR[trimmed] || text;
}

/**
 * Localizes a task string to Arabic if isAr is true
 * @param {string} task
 * @param {boolean} isAr
 * @returns {string}
 */
export function translateTask(task, isAr = false) {
  if (!task || typeof task !== 'string') return task || '';
  if (!isAr) return task;

  const trimmed = task.trim();

  // Direct match in dictionary
  if (TASK_TRANSLATIONS_AR[trimmed]) {
    return TASK_TRANSLATIONS_AR[trimmed];
  }

  // Handle patterns like "2 hour", "2 hours", "1 hour", "3 hours", etc.
  const hourMatch = trimmed.match(/^(\d+)\s*hours?$/i);
  if (hourMatch) {
    const num = parseInt(hourMatch[1], 10);
    if (num === 1) return 'ساعة واحدة';
    if (num === 2) return 'ساعتان';
    if (num >= 3 && num <= 10) return `${num} ساعات`;
    return `${num} ساعة`;
  }

  // Handle reversed pattern like "hour 2"
  const revHourMatch = trimmed.match(/^hours?\s*(\d+)$/i);
  if (revHourMatch) {
    const num = parseInt(revHourMatch[1], 10);
    if (num === 1) return 'ساعة واحدة';
    if (num === 2) return 'ساعتان';
    if (num >= 3 && num <= 10) return `${num} ساعات`;
    return `${num} ساعة`;
  }

  return task;
}

